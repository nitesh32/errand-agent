import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Harness } from './harness.ts';
import { checkInvariants } from './invariants.ts';
import { SCENARIOS } from './scenarios.ts';
import type { Scenario } from './scenarios.ts';

const DOCS = join(dirname(fileURLToPath(import.meta.url)), '..', '..', 'docs');
const TRACE_SCENARIO = 'Timeout after success';

interface Result {
  scenario: Scenario;
  passed: boolean;
  actual: string[];
  notes: string[];
  harness: Harness;
}

async function runScenario(scenario: Scenario): Promise<Result> {
  const harness = new Harness(scenario.options);
  const actual: string[] = [];
  const notes: string[] = [];
  try {
    await scenario.run(harness, (passed, description) => {
      actual.push(description);
      if (!passed) notes.push(`failed: ${description}`);
    });
  } catch (error) {
    notes.push(`threw: ${error instanceof Error ? error.message : String(error)}`);
  }
  notes.push(...checkInvariants(harness).map((problem) => `invariant: ${problem}`));
  return { scenario, passed: notes.length === 0, actual, notes, harness };
}

const cell = (text: string) => text.replace(/\|/g, '\\|').replace(/\n/g, ' ');

function renderTable(results: Result[]): string {
  const passed = results.filter((result) => result.passed).length;
  const rows = results.map(({ scenario, passed: ok, actual, notes }) =>
    [scenario.name, scenario.expected, actual.join('; '), ok ? 'pass' : 'FAIL', notes.join('; ') || `covers ${scenario.covers}`].map(cell).join(' | '),
  );
  return [
    '# Eval table',
    '',
    'Generated by `npm test`. Do not edit by hand. Runs offline against a scripted model and a seeded mock provider.',
    '',
    `**${passed} of ${results.length} scenarios passed.** Every scenario is also checked against these invariants: no duplicate bookings, no side effect without a user-granted approval that matches it, no unverified success claim, no retry before a status check, only legal state transitions, review text never reaches the model, limits hold, no secrets in traces, every turn gets a reply.`,
    '',
    '| Scenario | Expected | Actual | Result | Notes |',
    '|---|---|---|---|---|',
    ...rows.map((row) => `| ${row} |`),
    '',
  ].join('\n');
}

function saveSampleTrace(results: Result[]): void {
  const { harness } = results.find((result) => result.scenario.name === TRACE_SCENARIO)!;
  const traces = join(DOCS, 'traces');
  mkdirSync(traces, { recursive: true });
  copyFileSync(harness.tracer.fileOf(harness.session().runId), join(traces, 'timeout-after-success.jsonl'));
}

const results: Result[] = [];
for (const scenario of SCENARIOS) results.push(await runScenario(scenario));

mkdirSync(DOCS, { recursive: true });
writeFileSync(join(DOCS, 'eval-table.md'), renderTable(results));
saveSampleTrace(results);

for (const { scenario, passed, notes } of results) {
  console.log(`${passed ? 'pass' : 'FAIL'}  ${scenario.name}${passed ? '' : `\n      ${notes.join('\n      ')}`}`);
}
const failures = results.filter((result) => !result.passed).length;
console.log(`\n${results.length - failures} of ${results.length} scenarios passed. Table written to docs/eval-table.md`);
process.exitCode = failures ? 1 : 0;
